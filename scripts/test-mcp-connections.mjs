import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const values = new Map();
const config = { budgetApi: { url: 'https://budget.example/functions/v1/budget-api', mcpUrl: '' } };
const mod = { exports: {} };
new Function('require', 'module', 'exports', ts.transpileModule(fs.readFileSync('src/integrations/mcp/connections.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText)(name => name.includes('async-storage') ? { getItem: async k => values.get(k), setItem: async (k,v) => values.set(k,v) } : { config }, mod, mod.exports);
const { loadBudgetMcp, saveBudgetMcp, budgetMcpEndpoint, validateBudgetEndpoint } = mod.exports;
const endpoint = 'https://budget.example/functions/v1/budget-mcp';
assert.deepEqual(await loadBudgetMcp(), { endpoint, enabled: false });
assert.equal(await budgetMcpEndpoint(), null);
for (const url of ['https://attacker.example/functions/v1/budget-mcp', endpoint+'?secret=1', endpoint+'#x', 'http://budget.example/functions/v1/budget-mcp', 'https://user@budget.example/functions/v1/budget-mcp']) assert.throws(() => validateBudgetEndpoint(url));
await saveBudgetMcp({ endpoint, enabled: true });
assert.equal(await budgetMcpEndpoint(), endpoint);
await saveBudgetMcp({ endpoint, enabled: false });
assert.equal(await budgetMcpEndpoint(), null);
config.budgetApi.mcpUrl = endpoint;
assert.equal(await budgetMcpEndpoint(), null, 'explicit off overrides environment');
values.clear();
assert.equal(await budgetMcpEndpoint(), endpoint, 'existing environment remains compatible');
values.set('vora_mcp_connections_v1', 'broken');
await assert.rejects(budgetMcpEndpoint, 'corrupt settings must not silently fall back');
console.log('MCP connections: persistence, opt-out, environment compatibility and credential destination checks passed.');
values.clear();
const { defaultBudgetMcpEndpoint, loadBudgetMcpForSettings } = mod.exports;
config.budgetApi.url = ' https://budget.example/functions/v1/budget-api/ ';
assert.equal(defaultBudgetMcpEndpoint(), endpoint);
config.budgetApi.mcpUrl = 'https://old.example/functions/v1/budget-mcp';
let draft = await loadBudgetMcpForSettings();
assert.equal(draft.endpoint, endpoint);
assert.equal(draft.enabled, false);
assert.ok(draft.notice);
await assert.rejects(budgetMcpEndpoint, 'stale env must not be used silently');
values.set('vora_mcp_connections_v1', JSON.stringify({'daily-budget':{endpoint:'https://old.example/functions/v1/budget-mcp',enabled:true}}));
draft = await loadBudgetMcpForSettings();
assert.equal(draft.endpoint, endpoint);
assert.equal(draft.enabled, false);
await assert.rejects(budgetMcpEndpoint, 'draft repair must not change runtime settings');
await saveBudgetMcp({endpoint:draft.endpoint,enabled:true});
assert.equal(await budgetMcpEndpoint(), endpoint);
config.budgetApi.url = 'https://budget.example/functions/v1/mcp-token';
assert.throws(defaultBudgetMcpEndpoint, /EXPO_PUBLIC_BUDGET_API_URL/);
console.log('MCP defaults: stale env and saved URLs repaired in settings only; explicit save required.');
